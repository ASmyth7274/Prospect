// Writes dist/sw.js with a precache list of every built file and a content-hashed cache name.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const dist = path.resolve('dist');
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(path.relative(dist, p).split(path.sep).join('/'));
  }
})(dist);
const precache = files.filter((f) => f !== 'sw.js' && !f.endsWith('.map'));
const hash = crypto.createHash('sha1');
for (const f of precache.sort()) hash.update(f + fs.statSync(path.join(dist, f)).size);
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by scripts/postbuild.mjs
const CACHE = 'prospect-${version}';
const PRECACHE = ${JSON.stringify(['./', ...precache.map((f) => './' + f)], null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('prospect-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // network-first for the page so updates arrive; fall back to the cached shell offline
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  // cache-first for hashed assets
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`sw.js written: ${precache.length} files, cache prospect-${version}`);
